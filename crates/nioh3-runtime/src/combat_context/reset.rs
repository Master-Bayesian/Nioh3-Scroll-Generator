pub(super) fn normal_owner(
    stat: &[u8],
    materializer: &[u8],
) -> Result<(Vec<u8>, Vec<u8>), RuntimeError> {
    if stat.len() != 0x900 || materializer.len() != 0xb00 {
        return Err(layout("normal reset input extent differs"));
    }
    let mut s = stat.to_vec();
    let mut d = materializer.to_vec();
    for &(start, end, value) in STAT {
        s[start..end].fill(value);
    }
    for &(start, end, value) in DAMAGE {
        d[start..end].fill(value);
    }
    // 3774DB -> 64A9BC takes the false argument when owner kind is zero;
    // that write precedes the 818B68 selected reset.
    s[0x7d0] = 0;
    Ok((s, d))
}
