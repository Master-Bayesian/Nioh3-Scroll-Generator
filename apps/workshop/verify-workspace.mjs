import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
const output='deliverables/frontend-v2/search-ui-demo-v2';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const checks=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
const check=(name,ok)=>{assert.ok(ok,name);checks.push(name)};
try{
 await page.goto('http://127.0.0.1:4178');
 check('Five search sections start closed',await page.locator('.panel-toggle[aria-expanded=false]').count()===5);
 await page.getByRole('button',{name:'主副词条',exact:true}).click();
 await page.getByRole('button',{name:'恩宠',exact:true}).click();
 check('One open section per left column',await page.getByRole('button',{name:'主副词条',exact:true}).getAttribute('aria-expanded')==='false');
 await page.getByRole('button',{name:'敌人',exact:true}).click();
 await page.getByRole('button',{name:'特殊规则',exact:true}).click();
 check('One open section per right column',await page.getByRole('button',{name:'敌人',exact:true}).getAttribute('aria-expanded')==='false');
 const header=await page.getByRole('button',{name:'地形影响与挑战次数',exact:true}).boundingBox();
 check('Last section header stays above search dock',header.y+header.height<(await page.locator('.search-dock').boundingBox()).y);
 const height=await page.locator('.selection').evaluate(e=>e.getBoundingClientRect().height);
 await page.getByRole('button',{name:'展开已选条件'}).click();
 check('Expanded selections overlay instead of moving layout',height===await page.locator('.selection').evaluate(e=>e.getBoundingClientRect().height));
 await page.getByRole('button',{name:'收起已选条件'}).click();
 const card=page.locator('.search-page .scroll');
 const initialHeight=await card.evaluate(e=>e.getBoundingClientRect().height);
 await page.getByRole('slider',{name:'滑动切换绘卷'}).fill('2');
 check('Slider selects second result',await page.getByRole('spinbutton',{name:'跳转到第几张'}).inputValue()==='2');
 await page.getByLabel('绘卷结果浏览',{exact:true}).focus();
 await page.keyboard.press('ArrowDown');
 check('Down arrow selects next result',await page.getByRole('spinbutton',{name:'跳转到第几张'}).inputValue()==='3');
 check('Record height independent of contents',initialHeight===await card.evaluate(e=>e.getBoundingClientRect().height));
 check('Six effects and three rule rows reserved',await card.locator('.effect-line').count()===6&&await card.locator('.scroll-rule').count()===3);
 await card.hover();await page.mouse.wheel(0,-120);
 await page.waitForFunction(()=>document.querySelector('[aria-label="跳转到第几张"]').value==='2');
 checks.push('Mouse wheel switches results');
 await page.getByRole('button',{name:'加入购物车',exact:true}).click();
 await page.getByRole('slider',{name:'滑动切换绘卷'}).fill('1');
 await page.getByRole('button',{name:'加入购物车',exact:true}).click();
 await page.getByRole('button',{name:'查看购物车（2）'}).click();
 check('Cart compares two records',await page.locator('.cart-review .scroll').count()===2);
 await page.keyboard.press('Escape');
 await page.getByRole('radio',{name:'关闭游戏后添加到存档'}).check();
 check('Install mode selectable',await page.getByRole('radio',{name:'关闭游戏后添加到存档'}).isChecked());
 await page.getByRole('button',{name:'主副词条',exact:true}).click();
 const grip=page.locator('.selected-row .drag-grip').first();
 const source=await grip.boundingBox(),target=await page.locator('.selected-row').nth(1).boundingBox();
 await page.mouse.move(source.x+5,source.y+5);await page.mouse.down();
 await page.mouse.move(target.x+20,target.y+10,{steps:5});
 check('Opaque drag preview visible',await page.locator('.drag-preview').isVisible());
 await page.mouse.up();
 check('Drag preview clears on release',await page.locator('.drag-preview').count()===0);
 check('Drag source placeholder clears',await page.locator('[data-drag-source=true]').count()===0);
 await page.screenshot({path:`${output}/expanded-preview.png`,fullPage:true});
 await page.getByRole('button',{name:'绘卷编辑',exact:true}).click();
 check('Editor starts closed',await page.locator('.editor-section[open]').count()===0);
 await page.getByText('主副词条 · 长期保存',{exact:true}).click();
 await page.getByRole('textbox',{name:'编辑词条原始数值',exact:true}).fill('123');
 await page.getByRole('button',{name:'撤销',exact:true}).click();
 check('Undo restores prior field',await page.getByRole('textbox',{name:'编辑词条原始数值',exact:true}).inputValue()==='5');
 await page.getByRole('button',{name:'重做',exact:true}).click();
 check('Redo reapplies field',await page.getByRole('textbox',{name:'编辑词条原始数值',exact:true}).inputValue()==='123');
 await page.getByText('高级原始字段',{exact:true}).click();
 check('Advanced summary has readable width',(await page.getByText('高级原始字段',{exact:true}).boundingBox()).width>120);
 await page.getByText('副本内容 · 临时修改',{exact:true}).click();
 check('Editor accordion is exclusive',await page.locator('.editor-section[open]').count()===1);
 check('Temporary capacity is read only until supported',await page.getByRole('textbox',{name:'临时修改挑战次数上限'}).getAttribute('readonly')!==null);
 check('Dungeon changes use catalog selectors',await page.locator('.temporary-fields select').count()>=5);
 await page.screenshot({path:`${output}/editor-preview.png`,fullPage:true});
 check('No runtime errors',!errors.length);
 await writeFile(`${output}/workspace-verification.json`,JSON.stringify({checks,errors},null,2));
 console.log(`${checks.length} workspace checks passed`);
}finally{await browser.close()}
