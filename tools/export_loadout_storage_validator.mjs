/** Precompile planner validation without runtime eval under the desktop CSP. */
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {writeFile} from 'node:fs/promises';
import schema from './loadout-storage-schema.mjs';
const ajv=new Ajv({code:{source:true,esm:true}});
let code=standaloneCode(ajv,ajv.compile(schema));
code=code.replaceAll('require("ajv/dist/runtime/ucs2length").default','ucs2length.default');
if(/\brequire\(/.test(code)) throw Error('Unexpected standalone runtime dependency');
code='import ucs2length from "ajv/dist/runtime/ucs2length.js";\n'+code;
await writeFile(new URL('../apps/workshop/loadout-storage-validator.mjs',import.meta.url),'// Generated by tools/export_loadout_storage_validator.mjs. Do not edit.\n'+code+'\n');
console.log('LOADOUT_STORAGE_VALIDATOR_OK');
